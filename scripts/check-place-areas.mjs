#!/usr/bin/env node
// Roman Guides Companion — Place area validation
//
// Le 27 aree canoniche sotto sono state confermate a mano (vedi
// docs/DataModel.md) e NON provengono dal Google Sheet — export_places.py
// (docs/GoogleSheets.md) rigenera places.json dal foglio e non conosce
// questa lista, quindi un futuro export potrebbe azzerarla in silenzio.
// Questo controllo fa fallire la build con un messaggio chiaro se succede,
// invece di lasciare che un'area sporca o nulla passi inosservata.

import { readFileSync } from 'fs';

const PLACES_PATH = 'src/data/places.json';

const CANONICAL_AREAS = [
  'Appia', 'Aventino', 'Borgo', 'Campidoglio', "Campo de' Fiori", 'Celio',
  'Circo Massimo', 'Colosseo', 'Esquilino', 'Fori', 'Ghetto', 'Largo Argentina',
  'Monti', 'Navona', 'Nomentano', 'Ostiense', 'Pantheon', 'Repubblica',
  'San Giovanni', 'San Saba', 'Testaccio', 'Trastevere', 'Trevi', 'Tridente',
  'Trieste', 'Vaticano', 'Villa Borghese',
];

const canonicalSet = new Set(CANONICAL_AREAS);

const places = JSON.parse(readFileSync(PLACES_PATH, 'utf8'));

const missing = places.filter((p) => !p.area);
const outOfCanon = places.filter((p) => p.area && !canonicalSet.has(p.area));

if (missing.length > 0 || outOfCanon.length > 0) {
  console.error(`❌ ${PLACES_PATH}: area validation failed.\n`);
  if (missing.length > 0) {
    console.error(`  Missing area (${missing.length}):`);
    missing.forEach((p) => console.error(`    - ${p.id}`));
  }
  if (outOfCanon.length > 0) {
    console.error(`  Area not in the 27 canonical names (${outOfCanon.length}):`);
    outOfCanon.forEach((p) => console.error(`    - ${p.id}: "${p.area}"`));
  }
  console.error(
    `\n  Canonical areas are confirmed by hand, not generated by export_places.py — see docs/DataModel.md.\n` +
      `  If this ran after a Google Sheet export, the export overwrote the confirmed areas; fix places.json before building.`
  );
  process.exit(1);
}

console.log(`✅ Place areas: ${places.length}/${places.length} places have one of the 27 canonical areas.`);
